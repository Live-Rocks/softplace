function sourceMessages([first, assistant, second]: Dialogue): RetrievalEvalDatasetV2["users"][number]["chunks"][number]["sourceMessages"] {
  return [
    { role: "user", content: first },
    { role: "assistant", content: assistant },
    { role: "user", content: second }
  ];
}

export const retrievalEvalDatasetV2: RetrievalEvalDatasetV2 = {
  ...retrievalEvalDatasetV1,
  version: "2.0.0",
  users: retrievalEvalDatasetV1.users.map((user) => {
    const userDialogues = dialogues[user.id];
    if (!userDialogues || userDialogues.length !== user.chunks.length) {
      throw new Error(`invalid_v2_dialogues:${user.id}`);
    }
    return {
      ...user,
      chunks: user.chunks.map((chunk, index) => ({
        ...chunk,
        sourceMessages: sourceMessages(userDialogues[index]!)
      }))
    };
  })
};

export function formatSourceMessages(messages: RetrievalEvalSourceMessage[]) {
  return messages.map((message) => `${message.role === "user" ? "使用者" : "安放"}：${message.content}`).join("\n");
}
